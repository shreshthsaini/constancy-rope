"""Real values for the F2 method diagram (f2_method.tex), written to f2_method_data.tex.

Every glyph in the diagram that carries a number comes from here:
  * RoPE wavelengths T_j = 2*pi / theta_j, theta_j = b^(-2j/D), D = 56, for the native base
    b = 1e4 and for SEGA's released base b' (ntk_factor read from the run sidecar).
  * Per-band log logit gains lambda_j = ln(tau g_j) on the width axis (q/k dims 72 + 2j) for
    released SEGA (out_krea/main/sega_official) and Constancy-TM (out_krea/mainsb/constancy_tm,
    SEGA base + temperature), same prompt and seed, at the middle denoising step.
  * ln tau = 2 ln(SEGA reference q/k gain) = 0.16 ln 4.
Example chosen by rule, not by eye: the first held-out prompt (row 8 of main2/prompts.jsonl),
seed 0, step 14 of 28. Pure standard library; run with any python3.
"""
from __future__ import annotations

import glob
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = Path("/scratch/09032/saini_2/constancy_rope/out_krea")
ROW, STEP, D = 8, 14, 56
STACK = (6, 8, 10, 12)       # bands drawn in the stack: wavelengths comparable to the 256-token grid
BASE_BAND = 8                # band used for the base b -> b' inset


def sidecar(root: str, method: str, pid: str) -> dict:
    (path,) = glob.glob(str(OUT / root / method / "4096x4096" / f"{pid}_*_seed0.json"))
    return json.loads(Path(path).read_text())


def main() -> None:
    rows = [json.loads(line) for line in (ROOT / ".agent/notes/main2/prompts.jsonl").open()]
    pid = rows[ROW]["id"]
    sega, ctm = sidecar("main", "sega_official", pid), sidecar("mainsb", "constancy_tm", pid)
    assert ctm["config"]["rope"]["method"] == "sega_official", "Constancy-TM must share SEGA's base"
    gs, gc = sega["gains"][STEP], ctm["gains"][STEP]
    assert gs["step"] == gc["step"] == STEP and abs(gs["sigma"] - gc["sigma"]) < 1e-9
    official = gs["official"]
    base = 1e4 * official["ntk_factor"]
    ln_tau = 2 * math.log(official["reference_qk_gain"])
    lam_s = [gs["log_g"][72 + 2 * j] for j in range(D // 2)]
    lam_c = [gc["log_g"][72 + 2 * j] for j in range(D // 2)]
    wavelength = lambda b, j: 2 * math.pi * b ** (2 * j / D)  # noqa: E731

    lines = [
        "% Generated by f2_method_data.py; do not edit by hand.",
        f"% prompt row {ROW} ({pid}), seed 0, step {STEP} of 28, sigma = {gs['sigma']:.4f}",
        f"% SEGA base b' = {base:.1f}; ln tau = {ln_tau:.5f}",
        f"\\def\\FtwoLnTau{{{ln_tau:.5f}}}",
        f"\\def\\FtwoSigma{{{gs['sigma']:.2f}}}",
        f"\\def\\FtwoStep{{{STEP}}}",
    ]
    stack = []
    for k, j in enumerate(STACK):
        stack.append(f"{k}/{j}/{wavelength(base, j):.3f}/{wavelength(1e4, j):.3f}/{lam_s[j]:.5f}/{lam_c[j]:.5f}")
    lines.append("% row index / j / T_j at b' / T_j at b / lambda SEGA / lambda Constancy-TM")
    lines.append(f"\\def\\FtwoStack{{{', '.join(stack)}}}")
    for letter, j in zip("ABCD", STACK):  # per-row wavelengths for the summed logit curves
        lines.append(f"\\def\\FtwoTn{letter}{{{wavelength(base, j):.3f}}}\\def\\FtwoTo{letter}{{{wavelength(1e4, j):.3f}}}")
    lines.append(f"\\def\\FtwoBaseBand{{{BASE_BAND}}}")
    lines.append(f"\\def\\FtwoBaseTnew{{{wavelength(base, BASE_BAND):.3f}}}")
    lines.append(f"\\def\\FtwoBaseTold{{{wavelength(1e4, BASE_BAND):.3f}}}")
    lines.append("% all 28 width-axis bands: j / lambda SEGA / lambda Constancy-TM")
    lines.append("\\def\\FtwoAll{" + ", ".join(f"{j}/{lam_s[j]:.5f}/{lam_c[j]:.5f}" for j in range(D // 2)) + "}")
    (HERE / "f2_method_data.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
