"""Real values and the sample thumbnail for the F2 method diagram (f2_method.tex).

Writes f2_method_data.tex (TeX macros) and f2_method_sample.jpg (the photo in panel a).
Every glyph in the diagram that carries a number comes from here:
  * RoPE wavelengths T_j = 2*pi / omega_j, omega_j = theta^(-2j/D), D = 56, for the native base
    theta = 1e4 and for SEGA's released base theta' (ntk_factor read from the run sidecar).
  * Per-band log logit gains ln g_{a,j} on the width axis (q/k dims 72 + 2j) for released SEGA
    (out_krea/main/sega_official) and Constancy-TM (out_krea/mainsb/constancy_tm, SEGA base and
    temperature), same prompt and seed, at the middle denoising step.
  * ln tau = 2 ln(SEGA reference q/k gain) = 0.16 ln 4.
  * The photo is that prompt's released-SEGA 4096^2 output, reduced with Lanczos only.
Example chosen by rule, not by eye: the first held-out prompt (row 8 of main2/prompts.jsonl),
seed 0, step 14 of 28. Run with the crope env from paper/figs (Pillow is needed for the JPEG).
"""
from __future__ import annotations

import glob
import json
import math
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = Path("/scratch/09032/saini_2/constancy_rope/out_krea")
ROW, STEP, D = 8, 14, 56
STACK = (6, 8, 10, 12)       # bands drawn in the stack: wavelengths comparable to the 256-token grid
THUMB_PX = 512               # drawn at 0.89 in, so about 580 dpi in print
JPEG_Q = 94


def sample(root: str, method: str, pid: str, ext: str) -> Path:
    (path,) = glob.glob(str(OUT / root / method / "4096x4096" / f"{pid}_*_seed0.{ext}"))
    return Path(path)


def main() -> None:
    rows = [json.loads(line) for line in (ROOT / ".agent/notes/main2/prompts.jsonl").open()]
    pid = rows[ROW]["id"]
    sega = json.loads(sample("main", "sega_official", pid, "json").read_text())
    ctm = json.loads(sample("mainsb", "constancy_tm", pid, "json").read_text())
    assert ctm["config"]["rope"]["method"] == "sega_official", "Constancy-TM must share SEGA's base"
    gs, gc = sega["gains"][STEP], ctm["gains"][STEP]
    assert gs["step"] == gc["step"] == STEP and abs(gs["sigma"] - gc["sigma"]) < 1e-9
    official = gs["official"]
    base = 1e4 * official["ntk_factor"]
    ln_tau = 2 * math.log(official["reference_qk_gain"])
    lam_s = [gs["log_g"][72 + 2 * j] for j in range(D // 2)]
    lam_c = [gc["log_g"][72 + 2 * j] for j in range(D // 2)]
    wavelength = lambda b, j: 2 * math.pi * b ** (2 * j / D)  # noqa: E731

    lines = [
        "% Generated by f2_method_data.py; do not edit by hand.",
        f"% prompt row {ROW} ({pid}), seed 0, step {STEP} of 28, sigma = {gs['sigma']:.4f}",
        f"% SEGA base theta' = {base:.1f}; ln tau = {ln_tau:.5f}",
        f"\\def\\FtwoLnTau{{{ln_tau:.5f}}}",
        f"\\def\\FtwoSigma{{{gs['sigma']:.2f}}}",
        f"\\def\\FtwoStep{{{STEP}}}",
        "% row index / j / T_j at theta' / T_j at theta / ln g SEGA / ln g Constancy-TM",
        "\\def\\FtwoStack{" + ", ".join(
            f"{k}/{j}/{wavelength(base, j):.3f}/{wavelength(1e4, j):.3f}/{lam_s[j]:.5f}/{lam_c[j]:.5f}"
            for k, j in enumerate(STACK)) + "}",
        "% all 28 width-axis bands: j / ln g SEGA / ln g Constancy-TM",
        "\\def\\FtwoAll{" + ", ".join(f"{j}/{lam_s[j]:.5f}/{lam_c[j]:.5f}" for j in range(D // 2)) + "}",
    ]
    (HERE / "f2_method_data.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))

    png = sample("main", "sega_official", pid, "png")
    with Image.open(png) as im:
        thumb = im.convert("RGB").resize((THUMB_PX, THUMB_PX), Image.Resampling.LANCZOS)
    jpg = HERE / "f2_method_sample.jpg"
    thumb.save(jpg, "JPEG", quality=JPEG_Q, subsampling=0, optimize=True)
    print(f"{jpg.name}: {THUMB_PX} px from {png.name}, {jpg.stat().st_size / 1e3:.0f} kB")


if __name__ == "__main__":
    main()
