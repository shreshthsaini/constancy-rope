"""F6: SEGA as printed in the paper versus the released code.

Regenerate:  OMP_NUM_THREADS=8 /work/09032/saini_2/vista/library/uv-envs/crope/bin/python f6_sega_code.py

(a) Per-pair log logit gain over the 28 denoising steps, read from the JSON sidecars of the eight Krea dev
    prompts (out_krea/pilot/<method>/4096x4096/*.json, rows 0-7, seed 0), median over prompts. Rows are the
    28 rotary pairs of each spatial axis (dims 16-71 height, 72-127 width; both dims of a pair are equal),
    pair 0 = highest frequency. Separate released/paper colour scales are labelled explicitly.
    A common-scale line panel shows mean log gain per pair across all prompts and steps.
(b) Dev prompt 0 (the first manifest row, the prompt of Figure 5), seed 0, for the same four variants:
    Lanczos-reduced full frame (red box) and a native 384 x 256 px crop centred at (2048, 3072) (red frame).
Scores (written to f6_sega_code_table.tex, a booktabs tabular the paper inputs under the figure): mean over the
    eight dev prompts and the paired difference from SEGA (released) with a 95% percentile bootstrap CI (2,000
    resamples over prompts), from eval_krea/pilot/4096x4096/per_image.csv (CLIP score) and eval_krea/ir/pilot.csv
    (ImageReward).
Heatmaps use the paper's signed map (method blue, white, law orange) with one symmetric scale per group.
"""
import glob
import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.colors import LinearSegmentedColormap, Normalize

import crope_style as cs

S = cs.SCR
PID0 = "a4k_eval_4096_minus6873203881450547484"   # dev prompt 0
CROP = (2048 - 192, 3072 - 128, 2048 + 192, 3072 + 128)
# (method key, group, sub-label); groups share a header
VARIANTS = [("sega_official", "sega_official", "per-step"),
            ("sega_official_static", "sega_official", "static"),
            ("sega", "sega", "per-step"),
            ("sega_static", "sega", "static")]


def gains(method):
    files = sorted(glob.glob(str(S / "out_krea" / "pilot" / method / "4096x4096" / "*.json")))
    assert len(files) == 8, (method, len(files))
    order = cs.prompt_order()
    out, ids = [], []
    for f in files:
        j = json.load(open(f))
        c = j["config"]
        assert c["method"] == method and c["res"] == "4096x4096" and c["seed"] == 0 and order[c["prompt_id"]] < 8
        lg = np.array([g["log_g"] for g in j["gains"]])          # (28 steps, 128 dims)
        assert lg.shape == (28, 128) and np.allclose(lg[:, 0::2], lg[:, 1::2])
        out.append(lg[:, 16::2])                                  # 56 pairs: 28 height then 28 width
        ids.append(c["prompt_id"])
    return np.median(np.array(out), 0), ids, np.array(out)                       # (28 steps, 56 pairs)


def metrics():
    """Mean over the 8 dev prompts and the paired delta vs released SEGA with its 95% bootstrap CI."""
    d = pd.read_csv(S / "eval_krea" / "pilot" / "4096x4096" / "per_image.csv")
    ir = pd.read_csv(S / "eval_krea" / "ir" / "pilot.csv")
    keys = ["method", "prompt_id", "res"]
    d = d.merge(ir[keys + ["imagereward", "png"]], on=keys, how="inner", validate="one_to_one")
    assert (d.path == d.png).all(), "metrics and ImageReward scored different files"
    d = d[d.method.isin([v[0] for v in VARIANTS]) & (d.res == "4096x4096")]
    res = {}
    for m, _, _ in VARIANTS:
        a = d[d.method == m]
        assert len(a) == 8 and (a.seed == 0).all()
        res[m] = {k: (a[k].mean(), None if m == "sega_official" else cs.paired(d, m, k)[:4])
                  for k in ("clip", "imagereward")}
    return res


def num(fmt, x, sign=False):
    t = (("+" if sign and x > 0 else "") + fmt.format(x)).replace("-", "\u2212")
    return t


def add_ax(fig, x, top, w, h):
    W, H = fig.get_size_inches()
    return fig.add_axes([x / W, 1 - (top + h) / H, w / W, h / H])


SIGNED = LinearSegmentedColormap.from_list("signed", [cs.METHOD, "#FFFFFF", cs.LAW])   # paper-wide signed map
GROUP = {"sega_official": "Released", "sega": "Paper eqs."}
TABLE_NAME = {"sega_official": r"\segaofficial", "sega_official_static": r"\segaofficialstatic",
              "sega": r"\segapaper", "sega_static": r"\segapaperstatic"}


def tex_num(fmt, x, sign=False):
    return "$" + ("+" if sign and x > 0 else "") + fmt.format(x) + "$"


def write_table(M, path):
    """Booktabs tabular of the 16 score cells (4 variants x CLIP and ImageReward x mean and paired difference)."""
    shade = r"\cellcolor{cMethodShade}"
    lines = [
        "% Generated by figs/f6_sega_code.py; do not edit by hand. Eight dev prompts (rows 0-7), seed 0.",
        "% Paired difference from SEGA (released) with a 95% percentile bootstrap interval (2,000 resamples).",
        r"\providecolor{cMethodShade}{HTML}{E6F0F6}",
        r"\begin{tabular}{l rr rr}",   # no @{} edges: colortbl shading then ends with the rules
        r"\toprule",
        r" & \multicolumn{2}{c}{CLIP score$\uparrow$} & \multicolumn{2}{c}{ImageReward$\uparrow$} \\",
        r"\cmidrule(lr){2-3}\cmidrule(l){4-5}",
        r"Variant & Mean & $\Delta$ [95\% CI] & Mean & $\Delta$ [95\% CI] \\",
        r"\midrule",
    ]
    for m, _, _ in VARIANTS:
        cells = [TABLE_NAME[m]]
        for key in ("clip", "imagereward"):
            fmt = "{:.%df}" % cs.METRIC_PRECISION[key]
            mean, delta = M[m][key]
            cells.append(tex_num(fmt, mean))
            if delta is None:
                cells.append("reference")
            else:
                dm, lo, hi, n = delta
                assert n == 8
                cells.append(f"{tex_num(fmt, dm, sign=True)} [{tex_num(fmt, lo)}, {tex_num(fmt, hi)}]")
        if m == "sega_official":
            cells = [shade + c for c in cells]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    path.write_text("\n".join(lines))
    print("wrote", path.name)


def main():
    cs.style()
    G = {m: gains(m) for m, _, _ in VARIANTS}
    ids = G["sega_official"][1]
    assert all(set(G[m][1]) == set(ids) for m in G)
    M = metrics()
    vmax = np.ceil(max(np.abs(G[m][0]).max() for m in G) * 10) / 10
    released_max = np.ceil(max(np.abs(G[m][0]).max() for m in G if m.startswith("sega_official")) * 100) / 100
    norms = {"sega_official": Normalize(-released_max, released_max), "sega": Normalize(-vmax, vmax)}
    limits = {"sega_official": released_max, "sega": vmax}

    # ---- geometry (inches)
    W = cs.TEXT
    left = 0.47                        # heatmap y title, row names and ticks
    gin = 0.04                         # between the two columns of a group
    cb_gap, cb_w, cb_room = 0.06, 0.07, 0.30   # colorbar right of each group, then its tick labels
    ggap = 0.06                        # after the first colorbar's tick labels
    w = (W - left - 2 * gin - 2 * (cb_gap + cb_w + cb_room) - ggap) / 4
    xs = [left, left + w + gin]
    xs += [xs[1] + w + cb_gap + cb_w + cb_room + ggap]
    xs += [xs[2] + w + gin]
    TAG_A, HEAD_Y, SUB_Y = 0.13, 0.29, 0.45
    hm_top, hb, hgap = 0.50, 0.38, 0.10
    hm_bot = hm_top + 2 * hb + hgap
    prof_top, prof_h = hm_bot + 0.42, 0.52
    TAG_B = prof_top + prof_h + 0.43
    img_top = TAG_B + 0.08
    crop_h = w * 256 / 384
    crop_top = img_top + w + 0.03
    H = crop_top + crop_h + 0.21
    fig = plt.figure(figsize=(W, H))

    def fy(t):
        return 1 - t / H

    # ---- (a) group headers, column names and heatmaps
    for gi, grp in enumerate(("sega_official", "sega")):
        x0, x1 = xs[2 * gi], xs[2 * gi + 1] + w
        fig.text((x0 + x1) / 2 / W, fy(HEAD_Y), GROUP[grp], fontsize=cs.FS_LABEL, color=cs.INK, ha="center",
                 va="baseline")
        fig.add_artist(plt.Line2D([x0 / W, x1 / W], [fy(HEAD_Y + 0.045)] * 2, lw=0.6, color=cs.RULE,
                                  solid_capstyle="butt"))
    for (m, grp, sub), x0 in zip(VARIANTS, xs):
        fig.text((x0 + w / 2) / W, fy(SUB_Y), sub, fontsize=cs.FS_LABEL, color=cs.INK, ha="center", va="baseline")
    first = None
    for ci, ((m, grp, sub), x0) in enumerate(zip(VARIANTS, xs)):
        g = G[m][0]
        for bi, (name, sl) in enumerate((("Height", slice(0, 28)), ("Width", slice(28, 56)))):
            ax = add_ax(fig, x0, hm_top + bi * (hb + hgap), w, hb)
            if first is None:
                first = ax
            else:
                ax.sharex(first)
                ax.sharey(first)
            ax.pcolormesh(np.arange(0.5, 29), np.arange(-0.5, 28), g[:, sl].T, cmap=SIGNED, norm=norms[grp],
                          shading="flat", edgecolors="face", linewidth=0.25, antialiased=True,
                          rasterized=False)   # face-colored edges close the hairline seams between cells
            ax.set_xlim(0.5, 28.5)
            ax.set_ylim(27.5, -0.5)
            ax.set_xticks([7, 14, 21, 28])
            ax.set_yticks([0, 27])
            ax.tick_params(length=2, width=0.5, pad=1.5, labelsize=cs.FS_TICK, colors=cs.INK2, labelcolor=cs.INK)
            for sp in ax.spines.values():
                sp.set_linewidth(0.5)
                sp.set_color(cs.RULE)
            if bi == 0:
                ax.tick_params(labelbottom=False, bottom=False)
            if ci == 0:
                ax.set_ylabel(name, fontsize=cs.FS_LABEL, labelpad=1.5)
            else:
                ax.tick_params(labelleft=False, left=False)
            if bi == 1 and ci == 1:
                # one x title for the whole block, centred under the four columns
                ax.set_xlabel("Denoising step", fontsize=cs.FS_LABEL, labelpad=2)
                ax.xaxis.label.set_x(((xs[0] + xs[3] + w) / 2 - xs[1]) / w)   # y stays automatic
    # y title on the left column only, centred on the two rows
    fig.text(0.0, fy(hm_top + hb + hgap / 2), "Rotary pair", rotation=90, fontsize=cs.FS_LABEL, color=cs.INK,
             ha="left", va="center")
    # one slim colorbar per group, right of its two columns, spanning both rows; 3 ticks; log g on top
    for gi, grp in enumerate(("sega_official", "sega")):
        cx = xs[2 * gi + 1] + w + cb_gap
        cax = add_ax(fig, cx, hm_top, cb_w, 2 * hb + hgap)
        cb = fig.colorbar(plt.cm.ScalarMappable(norm=norms[grp], cmap=SIGNED), cax=cax)
        lim = limits[grp]
        cb.set_ticks([-lim, 0, lim])
        cb.set_ticklabels([num("{:g}", -lim), "0", num("{:g}", lim)])
        cb.ax.tick_params(labelsize=cs.FS_TICK, length=2, width=0.5, pad=1.5, colors=cs.INK2, labelcolor=cs.INK)
        cb.outline.set_linewidth(0.5)
        cb.outline.set_edgecolor(cs.RULE)
        cb.solids.set_rasterized(False)
        cb.solids.set_edgecolor("face")
        fig.text((cx + cb_w / 2) / W, fy(HEAD_Y), r"$\ln g$", fontsize=cs.FS_TICK, color=cs.INK, ha="center",
                 va="baseline")

    # ---- (a) mean log gain per pair, one shared axis for all four variants
    prof = add_ax(fig, left, prof_top, W - left - 0.66, prof_h)
    cs.clean_axes(prof, grid="y")
    ends = {}
    for m, group, sub in VARIANTS:
        values = G[m][2].mean(axis=(0, 1)).reshape(2, 28).mean(axis=0)
        prof.plot(np.arange(28), values, color=cs.color(group), ls="--" if sub == "static" else "-", lw=1.0,
                  dash_capstyle="butt", solid_capstyle="round")
        ends.setdefault(group, []).append(values[-1])
    prof.axhline(0, color=cs.RULE, lw=0.6, zorder=1)
    prof.set_xlim(0, 27)
    prof.set_xticks([0, 9, 18, 27])
    prof.set_ylim(-0.5, 1.35)
    prof.set_yticks([-0.5, 0, 0.5, 1.0])
    prof.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: num("{:g}", v)))
    prof.set_xlabel("Rotary pair", fontsize=cs.FS_LABEL, labelpad=2)
    prof.set_ylabel(r"Mean $\ln g$", fontsize=cs.FS_LABEL, labelpad=3)
    # direct labels at the right end of each pair of lines, nudged apart by 3 pt so they do not touch
    for group, lab, dy in (("sega_official", "released", 3.0), ("sega", "paper eqs.", -3.0)):
        prof.annotate(lab, xy=(27, float(np.mean(ends[group]))), xytext=(4, dy), textcoords="offset points",
                      fontsize=cs.FS_LABEL, color=cs.INK, ha="left", va="center", annotation_clip=False)

    # ---- (b) full frames with the crop window (red box) and the native crop below (red frame)
    s = 768 / 4096
    for ci, ((m, grp, sub), x0) in enumerate(zip(VARIANTS, xs)):
        png = glob.glob(str(S / "out_krea" / "pilot" / m / "4096x4096" / f"{PID0}_*.png"))
        assert len(png) == 1
        side = json.load(open(png[0][:-4] + ".json"))
        assert side["config"]["prompt_id"] == PID0 and side["config"]["seed"] == 0
        ax = add_ax(fig, x0, img_top, w, w)
        ax.imshow(cs.thumb(png[0], 768), interpolation="none")
        ax.set_axis_off()
        cs.crop_box(ax, (CROP[0] * s - 0.5, CROP[1] * s - 0.5, (CROP[2] - CROP[0]) * s, (CROP[3] - CROP[1]) * s))
        cax2 = add_ax(fig, x0, crop_top, w, crop_h)
        cax2.imshow(cs.crop(png[0], CROP), interpolation="none")
        cax2.set_axis_off()
        cs.crop_frame(cax2)
        name = f"{GROUP[grp]}, {sub}"
        fig.text((x0 + w / 2) / W, fy(crop_top + crop_h + 0.15), name, fontsize=cs.FS_LABEL, color=cs.INK,
                 ha="center", va="baseline", fontweight="bold" if m == "sega_official" else "normal")

    cs.panel_tag(fig, 0.0, fy(TAG_A), "a", "Gains per pair")
    cs.panel_tag(fig, 0.0, fy(TAG_B), "b", "Samples")
    print(f"figure size {W:.2f} x {H:.3f} in; columns {w:.3f} in; crop tiles {crop_h:.3f} in")
    cs.finish(fig, str(cs.HERE / "f6_sega_code"), photo=True, formats=("pdf", "svg"))
    write_table(M, cs.HERE / "f6_sega_code_table.tex")
    for m in G:
        g = G[m][0]
        print(f"{m:22s} median log g range [{g.min():+.3f}, {g.max():+.3f}]  CLIP {M[m]['clip'][0]:.2f}"
              f"  IR {M[m]['imagereward'][0]:.3f}  deltas {M[m]['clip'][1]} {M[m]['imagereward'][1]}")


if __name__ == "__main__":
    main()
